<section class="card-grid two">
    <article class="card"><p class="tag">NRC</p><h2>Noise Reduction Coefficient</h2><p>Shows how much sound a surface absorbs. Acoustic tiles, baffles, and perforated gypsum improve NRC and reduce echo.</p></article>
    <article class="card"><p class="tag">STC</p><h2>Sound Transmission Class</h2><p>Rates airborne sound isolation. Board mass, cavity insulation, decoupling, and sealing affect STC.</p></article>
    <article class="card"><p class="tag">RT</p><h2>Reverberation Time</h2><p>The time sound takes to decay in a room. Offices, classrooms, cinemas, mosques, and restaurants each need different targets.</p></article>
    <article class="card"><p class="tag">Flanking</p><h2>Indirect sound paths</h2><p>Sound can bypass walls through slabs, ducts, ceiling voids, doors, glazing, and service penetrations.</p></article>
</section>
